"""Opaque entity identifiers: ``<prefix>_<ULID>``, e.g. ``clip_01JB6Z4Q2X8M7T3V9KD0R5WFHN``.

Ids are generated once and never reused or recomputed from content (08 §1 "Entity IDs").
They sort by creation time; within one millisecond the generator is monotonic.
Code must treat ids as opaque strings: never parse times or bounds out of them.
"""

import os
import re
import threading
import time
from typing import Final

from ulid import ULID

PROJECT: Final = "prj"
ASSET: Final = "ast"
SYNC_GROUP: Final = "sgp"
BEAT: Final = "beat"
CLIP: Final = "clip"
TRANSITION: Final = "tr"
OVERLAY: Final = "ovl"
MARKER: Final = "mrk"
CONSTRAINT: Final = "cst"
TRANSCRIPT_EDIT: Final = "ted"
SEGMENT: Final = "seg"
SHOT: Final = "shot"
JOB: Final = "job"
RUN: Final = "run"

_PREFIX_RE = re.compile(r"^[a-z][a-z0-9]{0,7}$")
_ID_RE = re.compile(r"^([a-z][a-z0-9]{0,7})_([0-9A-HJKMNP-TV-Z]{26})$")

_lock = threading.Lock()
_last_ms = -1
_last_rand = 0
_RAND_BITS = 80


def _next_ulid() -> ULID:
    global _last_ms, _last_rand
    with _lock:
        now_ms = time.time_ns() // 1_000_000
        if now_ms <= _last_ms:
            now_ms = _last_ms
            _last_rand += 1
            if _last_rand >> _RAND_BITS:  # randomness overflow: borrow the next millisecond
                now_ms += 1
                _last_rand = int.from_bytes(os.urandom(10), "big") >> 1
        else:
            # Top bit cleared so increments within the same millisecond never overflow.
            _last_rand = int.from_bytes(os.urandom(10), "big") >> 1
        _last_ms = now_ms
        value = (now_ms << _RAND_BITS) | _last_rand
        return ULID.from_int(value)


def new_id(prefix: str) -> str:
    """New unique id ``<prefix>_<ULID>``. ``prefix``: lowercase, 1-8 chars."""
    if not _PREFIX_RE.match(prefix):
        raise ValueError(f"invalid id prefix: {prefix!r}")
    return f"{prefix}_{_next_ulid()}"


def is_id(value: str, prefix: str | None = None) -> bool:
    """True when ``value`` looks like an id generated by :func:`new_id`."""
    m = _ID_RE.match(value)
    return m is not None and (prefix is None or m.group(1) == prefix)


def id_prefix(value: str) -> str | None:
    m = _ID_RE.match(value)
    return m.group(1) if m else None
